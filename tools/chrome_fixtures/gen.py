#!/usr/bin/env python3
"""Converts Chrome-generated flexbox fixtures into hooke's line-oriented fixture format.

Usage (run from anywhere, always with -I so nothing is imported from the data directories):

    python3 -I tools/chrome_fixtures/gen.py TAFFY_CHECKOUT [CEPHAL_XML CEPHAL_DIVERGENCES_MD]

TAFFY_CHECKOUT is a checkout of https://github.com/DioxusLabs/taffy at tag v0.15.1; its
`tests/xml/flex/*.xml` files (generated by Taffy's `scripts/gentest` from
`test_fixtures/flex/*.html` in Chrome) are the input. The optional CEPHAL_XML is
`tests/fixtures/cephal.xml` from https://github.com/zortax/cephal (same XML schema, many tests in
one file); only the fixtures named in its `TAFFY_DIVERGENCES.md` are converted.

Output, relative to the repository root (this script's grandparent directory):
    tests/fixtures/flex/<name>.txt          one file per in-scope Taffy fixture variant
    tests/fixtures/chrome_truth/<name>.txt  one file per in-scope cephal fixture variant
    tests/fixtures/skipped.txt              `<dir>/<name>\t<reason>` per skipped variant

The format is described in tests/fixtures/README.md. The XML is read with the standard library
only and never executed; nothing in the checkout is run.
"""

import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "tests", "fixtures")


class Skip(Exception):
    """The fixture uses something hooke cannot represent."""


NUM = r"-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?"
PX = re.compile(rf"^({NUM})px$")
PCT = re.compile(rf"^({NUM})%$")
NUMBER = re.compile(rf"^{NUM}$")

SIZE_KEYWORDS = {"auto", "min-content", "max-content", "fit-content", "stretch"}


def length(prop, value, allowed):
    """Normalises a CSS length. `allowed` is the set of keywords valid for the property; px and
    percentages are always allowed unless `allowed` contains the marker 'px-only'."""
    v = value.strip()
    if PX.match(v):
        return v
    if "px-only" in allowed:
        raise Skip(f"{prop}: {v} (only absolute lengths are supported)")
    if PCT.match(v):
        return v
    if v in allowed:
        return v
    raise Skip(f"{prop}: {v}")


def keyword(prop, value, allowed):
    v = value.strip()
    if v in allowed:
        return v
    if prop.startswith(("align-", "justify-")) and v.split()[0] in ("safe", "unsafe"):
        raise Skip(f"{prop}: {v} (overflow-alignment keywords are not supported)")
    raise Skip(f"{prop}: {v}")


def number(prop, value):
    v = value.strip()
    if not NUMBER.match(v):
        raise Skip(f"{prop}: {v}")
    return v


ALIGN_ITEMS = {"normal", "stretch", "flex-start", "flex-end", "center", "baseline", "start", "end", "self-start",
               "self-end"}
JUSTIFY_CONTENT = {"normal", "flex-start", "flex-end", "center", "space-between", "space-around", "space-evenly",
                   "start", "end", "stretch"}
ALIGN_CONTENT = {"normal", "flex-start", "flex-end", "center", "space-between", "space-around", "space-evenly",
                 "stretch", "start", "end"}
OVERFLOW = {"visible", "clip", "hidden", "scroll"}

SIZE = SIZE_KEYWORDS
MIN = SIZE_KEYWORDS
MAX = (SIZE_KEYWORDS - {"auto"}) | {"none"}
BASIS = SIZE_KEYWORDS | {"content"}
MARGIN = {"auto"}
INSET = {"auto"}
PLAIN = set()


def style(el, is_leaf):
    """Maps every attribute of an input element. Returns an ordered list of (key, value)."""
    a = dict(el.attrib)
    out = []

    def take(name):
        return a.pop(name, None)

    display = take("display") or "flex"  # absent: the base stylesheet's `div { display: flex }`
    if display == "block" and is_leaf:
        # A box with no child boxes lays out the same whatever its inner display type: an empty
        # box, or one anonymous line box of text sized by the Ahem model.
        display = "flex"
    if display not in ("flex", "none"):
        raise Skip(f"display: {display}")
    out.append(("display", display))
    # Absent attributes are the values the generator elides, which are Taffy's defaults.
    out.append(("position", keyword("position", take("position") or "static", {"static", "relative", "absolute"})))
    out.append(("box-sizing", keyword("box-sizing", take("box-sizing") or "border-box",
                                      {"border-box", "content-box"})))
    out.append(("direction", keyword("direction", take("direction") or "ltr", {"ltr", "rtl"})))

    wm = take("writing-mode")
    if wm is not None and wm != "horizontal-tb":
        raise Skip(f"writing-mode: {wm}")
    for unsupported in ("float", "clear", "text-align", "contain", "justify-items", "justify-self"):
        v = take(unsupported)
        if v is not None and v != "none":
            raise Skip(f"{unsupported}: {v}")
    for name in list(a):
        if name.startswith("grid-"):
            raise Skip(f"{name}: {a[name]}")
    lc = take("flex-line-count")
    if lc is not None and lc != "1":
        raise Skip(f"flex-line-count: {lc}")

    def opt(name, conv):
        v = take(name)
        if v is not None:
            out.append((name, conv(name, v)))

    opt("flex-direction", lambda p, v: keyword(p, v, {"row", "row-reverse", "column", "column-reverse"}))
    opt("flex-wrap", lambda p, v: keyword(p, v, {"nowrap", "wrap", "wrap-reverse"}))
    opt("overflow-x", lambda p, v: keyword(p, v, OVERFLOW))
    opt("overflow-y", lambda p, v: keyword(p, v, OVERFLOW))
    opt("scrollbar-width", number)
    opt("align-items", lambda p, v: keyword(p, v, ALIGN_ITEMS))
    v = take("align-self")
    if v is not None and v.strip() != "auto":
        out.append(("align-self", keyword("align-self", v, ALIGN_ITEMS)))
    opt("align-content", lambda p, v: keyword(p, v, ALIGN_CONTENT))
    opt("justify-content", lambda p, v: keyword(p, v, JUSTIFY_CONTENT))
    opt("flex-grow", number)
    opt("flex-shrink", number)
    opt("flex-basis", lambda p, v: length(p, v, BASIS))
    opt("order", number)
    opt("width", lambda p, v: length(p, v, SIZE))
    opt("height", lambda p, v: length(p, v, SIZE))
    opt("min-width", lambda p, v: length(p, v, MIN))
    opt("min-height", lambda p, v: length(p, v, MIN))
    opt("max-width", lambda p, v: length(p, v, MAX))
    opt("max-height", lambda p, v: length(p, v, MAX))
    opt("aspect-ratio", number)
    opt("row-gap", lambda p, v: length(p, v, PLAIN))
    opt("column-gap", lambda p, v: length(p, v, PLAIN))
    for side in ("top", "right", "bottom", "left"):
        opt(f"margin-{side}", lambda p, v: length(p, v, MARGIN))
    for side in ("top", "right", "bottom", "left"):
        opt(f"padding-{side}", lambda p, v: length(p, v, PLAIN))
    for side in ("top", "right", "bottom", "left"):
        opt(f"border-{side}", lambda p, v: length(p, v, {"px-only"}))
    for side in ("top", "right", "bottom", "left"):
        opt(side, lambda p, v: length(p, v, INSET))

    if a:
        name = sorted(a)[0]
        raise Skip(f"{name}: {a[name]} (unknown property)")
    return out


def escape_text(s):
    """Text values contain no whitespace, '=' or '\\' and are ASCII; anything else is `\\u{hex}`."""
    out = []
    for ch in s:
        if ch.isascii() and ch.isprintable() and not ch.isspace() and ch not in "\\=":
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return "".join(out)


def element_children(el):
    return [c for c in el if isinstance(c.tag, str)]


def emit_node(inp, exp, depth, lines):
    kids = element_children(inp)
    props = style(inp, not kids)
    ekids = [c for c in exp if c.tag == "node"]
    if len(kids) != len(ekids):
        raise Skip("expectation tree does not match input tree")
    if not kids and inp.text is not None:
        # Mirrors Taffy's tests/xml.rs: a leaf with text gets an Ahem text context (trimmed).
        props.append(("text", escape_text(inp.text.strip())))
    nums = [exp.get(k) for k in ("x", "y", "width", "height")]
    for k, n in zip(("x", "y", "width", "height"), nums):
        if n is None or not NUMBER.match(n):
            raise Skip(f"expectation {k}: {n}")
    body = " ".join(f"{k}={v}" for k, v in props)
    lines.append(f"{'  ' * depth}node {' '.join(nums)} {body}")
    for c, e in zip(kids, ekids):
        emit_node(c, e, depth + 1, lines)


def convert(test, source):
    """Returns (name, text) or raises Skip."""
    name = test.get("name")
    rounding = test.get("use-rounding", "true")
    if rounding not in ("true", "false"):
        raise Skip(f"use-rounding: {rounding}")
    vp = test.find("viewport")
    dims = []
    for k in ("width", "height"):
        v = (vp.get(k) if vp is not None else None) or "max-content"
        if not (PX.match(v) or v in ("max-content", "min-content")):
            raise Skip(f"viewport {k}: {v}")
        dims.append(v)
    roots = element_children(test.find("input"))
    eroots = [c for c in test.find("expectations") if c.tag == "node"]
    if len(roots) != 1 or len(eroots) != 1:
        raise Skip("not exactly one root")
    lines = [
        "# Generated by tools/chrome_fixtures/gen.py. Do not edit; regenerate instead.",
        f"source {source}",
        f"viewport {dims[0]} {dims[1]}",
        f"rounding {rounding}",
    ]
    emit_node(roots[0], eroots[0], 0, lines)
    return name, "\n".join(lines) + "\n"


def write_dir(sub, items, skipped):
    """items: list of (test element, source string). Writes files, appends to skipped."""
    d = os.path.join(OUT, sub)
    os.makedirs(d, exist_ok=True)
    for f in os.listdir(d):
        if f.endswith(".txt"):
            os.remove(os.path.join(d, f))
    written = 0
    for test, source in items:
        name = test.get("name")
        try:
            name, text = convert(test, source)
        except Skip as e:
            skipped.append((f"{sub}/{name}", str(e)))
            continue
        with open(os.path.join(d, name + ".txt"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        written += 1
    return written


def main(argv):
    if len(argv) not in (2, 4):
        sys.exit(__doc__)
    taffy = argv[1]
    xml_dir = os.path.join(taffy, "tests", "xml", "flex")
    items = []
    for f in sorted(os.listdir(xml_dir)):
        if f.endswith(".xml"):
            items.append((ET.parse(os.path.join(xml_dir, f)).getroot(), f"taffy-v0.15.1 tests/xml/flex/{f}"))
    skipped = []
    n_flex = write_dir("flex", items, skipped)
    print(f"flex: {len(items)} variants, {n_flex} written")

    if len(argv) == 4:
        cephal_xml, divergences = argv[2], argv[3]
        with open(divergences, encoding="utf-8") as fh:
            named = set(re.findall(r"`([a-z0-9_]+)`", fh.read()))
        tests = ET.parse(cephal_xml).getroot()
        picked = [(t, f"cephal tests/fixtures/cephal.xml#{t.get('name')}") for t in tests.iter("test")
                  if t.get("name").split("__")[0] in named]
        n_truth = write_dir("chrome_truth", picked, skipped)
        print(f"chrome_truth: {len(picked)} variants, {n_truth} written")

    skipped.sort()
    with open(os.path.join(OUT, "skipped.txt"), "w", encoding="utf-8", newline="\n") as fh:
        for name, reason in skipped:
            fh.write(f"{name}\t{reason}\n")
    print(f"skipped: {len(skipped)}")


if __name__ == "__main__":
    main(sys.argv)
